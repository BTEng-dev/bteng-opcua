"""``bteng-opcua`` command line interface.

    bteng-opcua harvest -s harvest.yaml -o nodes.yaml     # generate
    bteng-opcua harvest -s harvest.yaml -o nodes.yaml --check   # fail on drift
    bteng-opcua run trees/ -n nodes.yaml                  # run every tree
    bteng-opcua run trees/lock.xml -n nodes.yaml          # run one tree

The generated ``nodes.yaml`` is meant to be committed.  Trees then run fully
offline against it — the server is only contacted when you regenerate.

Servers that reject anonymous sessions need credentials, either in the spec's
``auth:`` section or as ``--username``/``--password`` (which take precedence,
so the spec file need not hold a password).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from bteng_opcua.discovery import (
    HarvestSpec,
    harvest_from_nodeset,
    harvest_from_server,
)

_HEADER = """\
# Generated by `bteng-opcua harvest` from {source}.
# Node addresses and types are read from the OPC UA information model.
# Re-run the command to refresh; sections other than `nodes:` are preserved.
"""


def _dump(definitions: list[dict], preserved: dict, source: str) -> str:
    body = str(
        yaml.safe_dump(
            {"nodes": definitions}, sort_keys=False, default_flow_style=False, width=100
        )
    )
    text = _HEADER.format(source=source) + "\n" + body
    if preserved:
        text += "\n" + str(
            yaml.safe_dump(
                preserved, sort_keys=False, default_flow_style=False, width=100
            )
        )
    return text


def _harvest(spec: HarvestSpec, args: argparse.Namespace) -> tuple[list[dict], list[str], str]:
    nodeset = args.nodeset or spec.nodeset
    server = args.server or spec.server

    # Prefer the offline model when both are configured: it needs no network and
    # is the source of truth for the model's shape.
    if nodeset and not args.from_server:
        defs, warns = harvest_from_nodeset(nodeset, spec.roots)
        return defs, warns, str(nodeset)
    if server:
        auth = spec.auth.merged_with(
            username=args.username,
            password=args.password,
            certificate_path=args.certificate,
            private_key_path=args.private_key,
        )
        defs, warns = harvest_from_server(
            server, spec.roots, timeout=args.timeout, auth=auth
        )
        return defs, warns, server
    raise SystemExit("Spec must set 'server:' or 'nodeset:' (or pass --server/--nodeset)")


def cmd_harvest(args: argparse.Namespace) -> int:
    spec_data = yaml.safe_load(Path(args.spec).read_text(encoding="utf-8")) or {}
    spec = HarvestSpec.from_dict(spec_data)

    definitions, warnings, source = _harvest(spec, args)

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    if warnings and args.strict:
        print(f"{len(warnings)} node(s) skipped and --strict is set", file=sys.stderr)
        return 2
    if not definitions:
        print("No nodes harvested — check the 'harvest:' roots", file=sys.stderr)
        return 2

    out = Path(args.output)

    # Keep any hand-written sections (blackboard:, report:, ...) across regens.
    preserved: dict = {}
    if out.exists():
        existing = yaml.safe_load(out.read_text(encoding="utf-8")) or {}
        preserved = {k: v for k, v in existing.items() if k != "nodes"}

    text = _dump(definitions, preserved, source)

    if args.check:
        if not out.exists():
            print(f"{out} does not exist", file=sys.stderr)
            return 1
        current = yaml.safe_load(out.read_text(encoding="utf-8")) or {}
        if current.get("nodes") == definitions:
            print(f"{out} is up to date ({len(definitions)} nodes)")
            return 0
        print(f"{out} is STALE — the information model has changed.", file=sys.stderr)
        old = {n["alias"] for n in current.get("nodes") or []}
        new = {n["alias"] for n in definitions}
        for alias in sorted(new - old):
            print(f"  + {alias}", file=sys.stderr)
        for alias in sorted(old - new):
            print(f"  - {alias}", file=sys.stderr)
        for alias in sorted(old & new):
            a = next(n for n in current["nodes"] if n["alias"] == alias)
            b = next(n for n in definitions if n["alias"] == alias)
            if a != b:
                print(f"  ~ {alias}: {a} -> {b}", file=sys.stderr)
        print("Re-run without --check to update.", file=sys.stderr)
        return 1

    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out} — {len(definitions)} nodes from {source}")
    for d in definitions:
        kind = "method" if d["data_type"] == "method" else d["data_type"]
        print(f"  {d['alias']:<28} {kind}")
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    from bteng_opcua.runtime import install_logging, run_trees

    # The CLI is the app layer, so this is where logging gets configured (the
    # library core and run_trees leave the host's logging untouched).
    install_logging(args.log, pretty=not args.plain)
    return run_trees(
        args.trees,
        args.nodes,
        presets=args.bb,
        timeout=args.timeout,
        pretty=not args.plain,
    )


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="bteng-opcua", description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="command", required=True)

    h = sub.add_parser("harvest", help="Generate nodes.yaml from an OPC UA model")
    h.add_argument("-s", "--spec", required=True, help="Harvest spec YAML")
    h.add_argument("-o", "--output", default="nodes.yaml", help="Output registry YAML")
    h.add_argument("--server", help="Override the spec's opc.tcp:// endpoint")
    h.add_argument("--nodeset", help="Override the spec's NodeSet2.xml path")
    h.add_argument("--from-server", action="store_true",
                   help="Browse the live server even when a nodeset is configured")
    h.add_argument("--username", help="Override the spec's auth.username")
    h.add_argument("--password", help="Override the spec's auth.password")
    h.add_argument("--certificate", help="Override the spec's auth.certificate_path")
    h.add_argument("--private-key", help="Override the spec's auth.private_key_path")
    h.add_argument("--check", action="store_true",
                   help="Do not write; exit 1 if the output file is out of date")
    h.add_argument("--strict", action="store_true",
                   help="Exit non-zero if any node was skipped")
    h.add_argument("--timeout", type=float, default=10.0, help="Server timeout (s)")
    h.set_defaults(func=cmd_harvest)

    r = sub.add_parser("run", help="Run behaviour tree(s) against a node registry")
    r.add_argument("trees", nargs="+",
                   help="Tree XML file(s), or a directory whose *.xml are all run")
    r.add_argument("-n", "--nodes", default="nodes.yaml",
                   help="Node registry YAML (default: nodes.yaml)")
    r.add_argument("--bb", action="append", default=[], metavar="KEY=VALUE",
                   help="Seed a blackboard key before each tree runs (repeatable)")
    r.add_argument("--timeout", type=float, default=60.0,
                   help="Per-tree timeout in seconds (default: 60)")
    r.add_argument("--plain", action="store_true",
                   help="Disable colour and emoji (for logs / CI)")
    r.add_argument("--log", default="INFO", help="Log level (DEBUG/INFO/WARNING)")
    r.set_defaults(func=cmd_run)
    return ap


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
